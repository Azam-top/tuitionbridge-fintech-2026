// Generates docs/DEPENDENCIES.md from the installed packages (versions + declared licenses).
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const pkg = JSON.parse(readFileSync("package.json", "utf8")) as { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
const read = (dir: string) => { try { return JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as { name: string; version: string; license?: string | { type: string }; licenses?: { type: string }[] }; } catch { return null; } };
const lic = (p: NonNullable<ReturnType<typeof read>>) => (typeof p.license === "string" ? p.license : p.license?.type ?? p.licenses?.map((l) => l.type).join(" OR ") ?? "UNKNOWN");

function direct(names: Record<string, string> | undefined) {
  return Object.keys(names ?? {}).sort().map((n) => { const p = read(join("node_modules", n)); return { name: n, version: p?.version ?? "?", license: p ? lic(p) : "?" }; });
}
const all = new Map<string, number>();
let total = 0;
function walk(root: string) {
  for (const e of readdirSync(root)) {
    if (e.startsWith(".")) continue;
    const dir = join(root, e);
    if (!statSync(dir).isDirectory()) continue;
    if (e.startsWith("@")) { walk(dir); continue; }
    const p = read(dir);
    if (p) { total++; const l = lic(p); all.set(l, (all.get(l) ?? 0) + 1); }
    const nested = join(dir, "node_modules");
    if (existsSync(nested)) walk(nested);
  }
}
walk("node_modules");
const table = (rows: ReturnType<typeof direct>) => rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n");
const md = `# Dependencies and licenses

Generated by \`npm run licenses\` from the installed \`node_modules\` (${new Date().toISOString().slice(0, 10)}). Licenses are as declared in each package's metadata; this is an inventory, not legal advice.

## Direct runtime dependencies
| Package | Version | License |
|---|---|---|
${table(direct(pkg.dependencies))}

## Direct development dependencies
| Package | Version | License |
|---|---|---|
${table(direct(pkg.devDependencies))}

## All installed packages (${total}), by declared license
| License | Packages |
|---|---|
${[...all.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`).join("\n")}

Notes: the project itself has no license file yet (team to choose). \`pdfjs-dist\` (Apache-2.0) is used only for text extraction from text-based PDFs. No fonts, images or datasets from third parties are bundled; all invoice, provider and account data is synthetic.
`;
writeFileSync("docs/DEPENDENCIES.md", md);
console.log(`docs/DEPENDENCIES.md written (${total} packages inventoried).`);
